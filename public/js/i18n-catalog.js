  const englishEntries = Object.entries(english);
  const englishReplacements = englishEntries
    .filter(([source]) => (source.match(/[\u3400-\u9fff]/g) || []).length > 1)
    .sort((left, right) => right[0].length - left[0].length);
  const englishTemplates = englishEntries
    .filter(([source]) => source.includes("{") && (source.replace(/\{[A-Za-z0-9_]+\}/g, "").match(/[\u3400-\u9fff]/g) || []).length >= 2)
    .map(([source, target]) => compileTemplate(source, target))
    .sort((left, right) => right.literalLength - left.literalLength);

  function normalizeLocale(locale) {
    const value = String(locale || "").trim().toLowerCase();
    if (value === "en" || value.startsWith("en-")) return "en";
    if (value === "zh" || value === "zh-cn" || value.startsWith("zh-")) return "zh-CN";
    return "";
  }

  function interpolate(message, params) {
    if (!params) return message;
    return String(message).replace(/\{([A-Za-z0-9_]+)\}/g, (match, key) => (
      Object.prototype.hasOwnProperty.call(params, key) ? String(params[key]) : match
    ));
  }

  function compileTemplate(source, target) {
    const keys = [];
    let cursor = 0;
    let pattern = "^";
    for (const match of source.matchAll(/\{([A-Za-z0-9_]+)\}/g)) {
      pattern += escapeRegExp(source.slice(cursor, match.index));
      pattern += "([\\s\\S]*?)";
      keys.push(match[1]);
      cursor = match.index + match[0].length;
    }
    pattern += `${escapeRegExp(source.slice(cursor))}$`;
    return { regex: new RegExp(pattern), keys, target, literalLength: source.replace(/\{[A-Za-z0-9_]+\}/g, "").length };
  }

  function escapeRegExp(value) {
    return String(value).replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
  }

  function translateTemplate(text) {
    for (const template of englishTemplates) {
      const match = text.match(template.regex);
      if (!match) continue;
      const params = {};
      template.keys.forEach((key, index) => {
        params[key] = match[index + 1];
      });
      return interpolate(template.target, params);
    }
    return "";
  }

  function translateFragment(locale, source) {
    const text = String(source ?? "");
    if (normalizeLocale(locale) !== "en" || !/[\u3400-\u9fff]/.test(text)) return text;
    const whitespaceMatch = text.match(/^(\s*)([\s\S]*?)(\s*)$/);
    const inner = whitespaceMatch?.[2] || text;
    const exact = english[inner] || translateTemplate(inner);
    if (exact) return `${whitespaceMatch?.[1] || ""}${exact}${whitespaceMatch?.[3] || ""}`;
    let translated = text;
    englishReplacements.forEach(([chinese, replacement]) => {
      if (translated.includes(chinese)) translated = translated.split(chinese).join(replacement);
    });
    return translated;
  }

  function translateKnown(locale, source, params) {
    const text = String(source ?? "");
    if (normalizeLocale(locale) !== "en") return interpolate(text, params);
    const translated = english[text] || translateTemplate(text) || text;
    return interpolate(translated, params);
  }

  function translate(locale, source, params) {
    const text = String(source ?? "");
    if (normalizeLocale(locale) !== "en") return interpolate(text, params);
    const translated = english[text] || translateTemplate(text) || translateFragment(locale, text);
    return interpolate(translated, params);
  }

  return {
    defaultLocale: "zh-CN",
    supportedLocales: Object.freeze(["zh-CN", "en"]),
    english,
    normalizeLocale,
    translate,
    translateFragment,
    translateKnown,
  };
